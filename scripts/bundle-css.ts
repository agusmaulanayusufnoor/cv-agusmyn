import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';

try {
  const css = readFileSync('public/css/style.css', 'utf8');
  if (!existsSync('src/styles')) {
    mkdirSync('src/styles', { recursive: true });
  }
  writeFileSync(
    'src/styles/compiledCss.ts',
    `// Auto-generated by scripts/bundle-css.ts — DO NOT EDIT DIRECTLY\nexport const compiledCss = ${JSON.stringify(css)};\n`
  );
  console.log('✓ Successfully bundled inline CSS into src/styles/compiledCss.ts');
} catch (err) {
  console.error('Failed to bundle CSS:', err);
  process.exit(1);
}
